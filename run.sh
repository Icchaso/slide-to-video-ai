#!/usr/bin/env bash
set -e

# カレントディレクトリをスクリプトのある場所へ移動
cd "$(dirname "$0")"

echo "========================================="
echo " 動画自動制作プロセスを開始します..."
echo "========================================="

# Python仮想環境のアクティベート
if [ -f "venv/bin/activate" ]; then
    source venv/bin/activate
else
    echo "エラー: 仮想環境が見つかりません。先に ./setup.sh を実行してください。"
    exit 1
fi

# メインスクリプトの実行
python3 src/main.py "$@"

echo "========================================="
echo " 処理が完了しました。output/ フォルダを確認してください。"
echo "========================================="
